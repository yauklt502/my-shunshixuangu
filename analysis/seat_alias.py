def classify_seat(name: str) -> Tuple[str, Optional[str]]:
    """返回 (大类, 游资别名或None)。"""
    if not name:
        return "未知", None
    n = str(name).strip()

    if n == "机构专用" or n.startswith("机构专用"):
        return "机构", "机构专用"
    if "沪股通" in n or "深股通" in n or n in {"沪股通专用", "深股通专用"}:
        return "北向资金", n
    if "东方财富" in n and any(x in n for x in ("拉萨", "山南", "日喀则", "林芝", "昌都")):
        return "东财散户通道", "拉萨天团/东财"

    for alias, needles in YOUZI_RULES:
        for needle in needles:
            if needle in n:
                return "知名游资", alias

    if "拉萨" in n and "东方财富" not in n:
        return "知名游资", "拉萨天团"

    if any(k in n for k in ("互联网", "网上")):
        return "量化/互联网席位", None

    return "其他营业部", None


def short_seat_name(name: str) -> str:
    n = str(name or "").strip()
    n = re.sub(r"股份有限公司|有限责任公司|有限公司", "", n)
    n = n.replace("证券营业部", "")
    return n
